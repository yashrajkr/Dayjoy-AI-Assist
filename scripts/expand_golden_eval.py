def main() -> None:
    with open(FIXTURE_PATH, encoding="utf-8") as f:
        existing = json.load(f)
    existing_messages = {c["message"] for c in existing}

    new_cases = []
    skipped = []
    for category, messages in MESSAGES.items():
        for msg in messages:
            if msg in existing_messages:
                skipped.append(msg)
                continue
            plan = build_plan(msg)
            new_cases.append({
                "message": msg,
                "expected_intent": plan.intent.intent,
                "expected_tools": plan.proposed_tools,
                "category": category,
            })
            existing_messages.add(msg)

    merged = existing + new_cases
    with open(FIXTURE_PATH, "w", encoding="utf-8") as f:
        json.dump(merged, f, indent=2, ensure_ascii=False)
        f.write("\n")

    print(f"existing: {len(existing)}")
    print(f"new: {len(new_cases)}")
    print(f"skipped (dupe): {len(skipped)}")
    print(f"total: {len(merged)}")

    from collections import Counter
    print("intent distribution (new only):", Counter(c["expected_intent"] for c in new_cases))
    print("category distribution (new only):", Counter(c["category"] for c in new_cases))


if __name__ == "__main__":
    main()
